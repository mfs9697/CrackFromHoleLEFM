"""Write figures_src/data/ua_constants.tex from figures_src/data/DATA_MANIFEST.json (AAM-UA7).
Every scalar constant is copied with repr() precision into a TeX macro \\uaC<name>; no value is computed here.
usage: python make_ua_constants.py [dataDir]"""
import json, os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
dd = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(here), 'figures_src', 'data')
M = json.load(open(os.path.join(dd, 'DATA_MANIFEST.json'), encoding='utf-8'))
L = ['% generated by make_ua_constants.py from DATA_MANIFEST.json -- do not edit']


WORDS = 'Zero One Two Three Four Five Six Seven Eight Nine'.split()
seen = {}


def name(k):
    s = ''.join(WORDS[int(ch)] if ch.isdigit() else ch for ch in k)   # digits spelled out: h0 / 2h0 / fig07 stay distinct
    n = 'uaC' + re.sub(r'[^A-Za-z]', '', s.title().replace('_', ''))
    assert seen.setdefault(n, k) == k, ('macro name collision', n, k, seen[n])
    return n


def put(prefix, d):
    for k, v in d.items():
        if isinstance(v, dict):
            put(prefix + k, v)
        elif isinstance(v, (int, float)) and not isinstance(v, bool):
            L.append('\\def\\%s{%s}' % (name(prefix + '_' + k if prefix else k), repr(float(v)) if isinstance(v, float) else str(v)))


put('', M['constants'])
# display string of a_LS with three decimals, as printed in the legends of Figs. 7-8 (rounding for display only)
L.append('\\def\\uaCAlsMmThreeDecimals{%.3f}' % M['constants']['aLS_mm'])
open(os.path.join(dd, 'ua_constants.tex'), 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
print('\n'.join(L))
