function S = build_twoleg_sharp_benchmark(C, varargin)
%BUILD_TWOLEG_SHARP_BENCHMARK  Elastic sharp two-leg crack from historical geometry.
%
% Both crack legs are traction-free.  The narrow channel is used only to
% generate a split mesh; its two faces are then projected onto C.Pmid.
% The common tip remains a single node, giving a sharp traction-free crack
% ending at V2.
%
% Name-value options
%   'AsymmetryLevel'  deterministic perturbation amplitude in units of h_tip
%                     applied only to upper-side interior nodes near V2.
%   'MeshScale'       multiplies Hmin/Hmax (default 1)
%   'Plot'            diagnostic plot
%
% Output S contains the T3/T6 meshes, displacement solution, material,
% crack polyline, and mesh-generation diagnostics.

    ip = inputParser;
    addParameter(ip,'AsymmetryLevel',0,@(x)isnumeric(x)&&isscalar(x)&&x>=0);
    addParameter(ip,'MeshScale',1,@(x)isnumeric(x)&&isscalar(x)&&x>0);
    addParameter(ip,'Plot',false,@(x)islogical(x)||isnumeric(x));
    parse(ip,varargin{:});

    alphaReq = ip.Results.AsymmetryLevel;
    meshScale = ip.Results.MeshScale;

    Pmid = C.Pmid;
    htip = C.delta/C.ncoh;
    Hmin = meshScale*htip;
    Hmax = meshScale*C.hmax;
    Hgrad = C.hgrad;

    [Bound,Ggeom] = build_domain_pencil_polyline( ...
        Pmid,C.A,C.B,C.chw, ...
        'join','miter','miter_limit',6,'corner_tol',1e-10,'tip','point');

    Gcol = [2;size(Bound,1);Bound(:,1);Bound(:,2)];
    gd = decsg(Gcol);
    mdl = createpde();
    geometryFromEdges(mdl,gd);

    msh = generateMesh(mdl, ...
        'Hmin',Hmin,'Hmax',Hmax,'Hgrad',Hgrad,'GeometricOrder','linear');

    coord0 = msh.Nodes.';
    conn0 = msh.Elements.';

    % Collapse both crack-face chains to the physical two-leg midline.
    coord3 = coord0;
    tolLine = max(1e-8*max(Hmin,1e-12),1e-12);

    Up = Ggeom.up_chain;
    Dn = Ggeom.dn_chain;

    for iseg=1:size(Pmid,1)-1
        a = Pmid(iseg,:);
        b = Pmid(iseg+1,:);

        iu = face_ids_on_segment(coord0,Up(iseg,:),Up(iseg+1,:),tolLine);
        id = face_ids_on_segment(coord0,Dn(iseg,:),Dn(iseg+1,:),tolLine);

        coord3(iu,:) = project_to_segment(coord0(iu,:),a,b);
        coord3(id,:) = project_to_segment(coord0(id,:),a,b);
    end

    % Force the common geometric tip to be exact.
    [~,iTip] = min(sum((coord3-C.V2).^2,2));
    coord3(iTip,:) = C.V2;

    % Remove any zero-area triangles generated by channel collapse.
    Atri = signed_tri_areas(conn0,coord3);
    areaTol = 1e-12*max(Hmin,1e-12)^2;
    keep = abs(Atri)>areaTol;
    conn3 = conn0(keep,:);
    Atri = Atri(keep);

    cw = Atri<0;
    if any(cw)
        tmp = conn3(cw,2);
        conn3(cw,2) = conn3(cw,3);
        conn3(cw,3) = tmp;
    end

    % Deliberate local asymmetry: perturb only interior T3 vertices above
    % the final crack segment, then back off automatically if needed.
    [coord3,alphaUsed,perturbedNodes] = perturb_upper_tip_patch( ...
        coord3,conn3,C,alphaReq,htip);

    % T3 -> T6.  Keep the parent T3 geometry for pointLocation diagnostics.
    [coord6,conn6] = T3toT6_fast(coord3,conn3);

    mesh = struct();
    mesh.coord = coord6;
    mesh.connect = conn6;
    mesh.coord3 = coord3;
    mesh.connect3 = conn3;

    mat = struct('E',C.E,'nu',C.nu,'D',C.Dmat,'Dmat',C.Dmat,'ps',C.ps);

    [nip2,xip2,w2,Nextr] = integr();
    quad = struct('nip2',nip2,'xip2',xip2,'w2',w2,'Nextr',Nextr);

    % Historical minimal rigid-body constraints.
    fixNodes = zeros(3,1);
    for k=1:3
        [~,fixNodes(k)] = min(sum((coord6-C.fix_points(k,:)).^2,2));
    end
    if numel(unique(fixNodes))<3
        error('build_twoleg_sharp_benchmark:BCNodeCollision', ...
            'Rigid-body constraint nodes are not distinct.');
    end
    fixvar = [2*fixNodes(1);2*fixNodes(2)-1;2*fixNodes(3)-1];

    K = stif_assem(mesh,mat,quad,fixvar);

    elod = edge_loads_T6(coord6,C.B,1e-8);
    F = zeros(2*size(coord6,1),1);
    for k=1:size(elod,1)
        dof = 2*elod(k,1);
        F(dof) = F(dof) + C.sigma0*elod(k,2);
    end
    F(fixvar)=0;

    U = K\F;

    if logical(ip.Results.Plot)
        figure('Name','Two-leg sharp benchmark mesh','Color','w'); clf;
        triplot(conn3,coord3(:,1),coord3(:,2)); hold on; axis equal; box on;
        plot(Pmid(:,1),Pmid(:,2),'r-','LineWidth',2);
        if ~isempty(perturbedNodes)
            plot(coord3(perturbedNodes,1),coord3(perturbedNodes,2),'ko','MarkerSize',3);
        end
        xlim([0,C.A]); ylim([-C.B,C.B]);
        title(sprintf('two-leg benchmark, asymmetry level used = %.3g',alphaUsed));
    end

    S = struct();
    S.C = C;
    S.mesh = mesh;
    S.mat = mat;
    S.U = U;
    S.V = Pmid;
    S.K = K;
    S.F = F;
    S.elod = elod;
    S.fixNodes = fixNodes;
    S.fixvar = fixvar;
    S.geometry = struct('Bound',Bound,'Ggeom',Ggeom,'model',mdl);
    S.meshInfo = struct( ...
        'Hmin',Hmin,'Hmax',Hmax,'Hgrad',Hgrad, ...
        'nT3nodes',size(coord3,1),'nT3elem',size(conn3,1), ...
        'nT6nodes',size(coord6,1),'nT6elem',size(conn6,1), ...
        'asymmetryLevelRequested',alphaReq, ...
        'asymmetryLevelUsed',alphaUsed, ...
        'perturbedNodes',perturbedNodes(:));
end


function ids = face_ids_on_segment(X,A,B,tol)
    AB = B-A;
    L2 = dot(AB,AB);
    if L2<=eps
        ids = zeros(0,1);
        return;
    end
    t = ((X-A)*AB.')/L2;
    Q = A + t.*AB;
    d = sqrt(sum((X-Q).^2,2));
    ids = find(t>=-1e-8 & t<=1+1e-8 & d<=tol);
end


function Xp = project_to_segment(X,A,B)
    AB=B-A;
    L2=dot(AB,AB);
    t=((X-A)*AB.')/L2;
    t=max(0,min(1,t));
    Xp=A+t.*AB;
end


function A = signed_tri_areas(T,X)
    v1=X(T(:,1),:);
    v2=X(T(:,2),:);
    v3=X(T(:,3),:);
    A=0.5*((v2(:,1)-v1(:,1)).*(v3(:,2)-v1(:,2)) - ...
           (v2(:,2)-v1(:,2)).*(v3(:,1)-v1(:,1)));
end


function [X,alphaUsed,idxMove] = perturb_upper_tip_patch(X0,T,C,alphaReq,h)
    X=X0;
    alphaUsed=0;
    idxMove=zeros(0,1);
    if alphaReq<=0
        return;
    end

    % Boundary vertices must remain fixed.
    TR=triangulation(T,X0);
    fb=freeBoundary(TR);
    bnodes=unique(fb(:));
    isBoundary=false(size(X0,1),1);
    isBoundary(bnodes)=true;

    tip=C.V2(:);
    xl=(C.R_loc*(X0-tip.').').';
    r=sqrt(sum(xl.^2,2));

    idx=find(~isBoundary & r>=C.perturb_rmin & r<=C.perturb_rmax & xl(:,2)>0);
    if isempty(idx)
        warning('build_twoleg_sharp_benchmark:NoPerturbNodes', ...
            'No interior upper-side nodes found in perturbation annulus.');
        return;
    end

    phase=13.37*xl(idx,1)/max(C.delta,eps) + 7.11*xl(idx,2)/max(C.delta,eps);
    dirLocal=[0.65*sin(phase), 0.85*cos(phase)];
    dGlobal=(C.R_gl*dirLocal.').';

    alpha=alphaReq;
    for attempt=1:8
        Xt=X0;
        Xt(idx,:)=Xt(idx,:)+alpha*h*dGlobal;
        At=signed_tri_areas(T,Xt);
        if all(At>1e-14*h^2)
            X=Xt;
            alphaUsed=alpha;
            idxMove=idx;
            return;
        end
        alpha=0.5*alpha;
    end

    warning('build_twoleg_sharp_benchmark:PerturbationRejected', ...
        'Could not apply a non-inverting perturbation; using unperturbed mesh.');
end
