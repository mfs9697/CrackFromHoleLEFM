function validate_isolated_fixed_result_cache(R,candidate,R0,checkpointFile)
% Prove accepted fixed-state reuse without reading U or repeating EDI/PCG.
id='isolatedtip:FixedReuseMismatch';
assert(R.pass&&all(structfun(@logical,R.gates))&& ...
    candidate.scientificallyReadyForIncrementalPhysicalSolve&& ...
    all(structfun(@logical,candidate.gates))&&all(structfun(@logical,candidate.syntheticGates)), ...
    id,'Saved fixed result/candidate contains failed gates.');
assert(R.nSegments==candidate.nSegments&& ...
    isequal(size(R.pathFixed),size(candidate.path))&& ...
    norm(R.pathFixed-candidate.path,'fro')<=2e-12&& ...
    abs(R.currentIncrementLength-candidate.currentIncrementLength)<=1e-14,id, ...
    'Saved fixed result has different geometry or increment.');
for name={'scale','hTip_m','rInner_m','rOuter_m','rCore_m', ...
        'expectedCoreT3','expectedEDIElements','expectedOptimizedSupport','expectedNativeSamples'}
    key=name{1};assert(isequal(R.coreMeshControls.(key)(:),candidate.coreMeshControls.(key)(:)), ...
        id,'Saved fixed result has a different core fingerprint: %s.',key);
end
assert(crack_exterior_controls_match(R.exteriorMeshControls,candidate.exteriorMeshControls, ...
    R.coreMeshControls.scale,candidate.coreMeshControls.scale),id, ...
    'Saved fixed result has a different exterior family.');
assert(exist(checkpointFile,'file')==2,id,'Accepted result requires its original physical checkpoint.');
s=load(checkpointFile,'mesh','mat','C','meta','solverInfo');
assert_crack_checkpoint_physics(s,candidate.mat,R0.C,id);
assert_crack_checkpoint_exterior(s,candidate,id);
[p6,t6]=T3toT6_fast(candidate.p,candidate.t);
assert(isequal(s.mesh.connect3,candidate.t)&&isequal(s.mesh.connect,t6)&& ...
    isequal(size(s.mesh.coord3),size(candidate.p))&& ...
    max(abs(s.mesh.coord3(:)-candidate.p(:)))<=1e-12&& ...
    isequal(size(s.mesh.coord),size(p6))&&max(abs(s.mesh.coord(:)-p6(:)))<=1e-12&& ...
    norm(s.meta.path-candidate.path,'fro')<=2e-12,id, ...
    'Saved fixed checkpoint is not the qualified T3/T6 geometry.');
assert(isequaln(R.solverInfo,s.solverInfo)&& ...
    R.EDI.EDI_elements==candidate.coreMeshControls.expectedEDIElements&& ...
    R.summary.T3_nodes==size(candidate.p,1)&&R.summary.T3_elements==size(candidate.t,1)&& ...
    R.summary.T6_nodes==size(p6,1),id,'Saved fixed summary/solver provenance differs.');
end
